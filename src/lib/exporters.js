import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import pptxgen from "pptxgenjs";
import { getMetrics, money, number } from "./analytics.js";
import { toCsv } from "./csv.js";

function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url; a.download = filename; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
function safeName(value) {
  return String(value || "marketing-report").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

export function exportCsv(rows, clientName, month) {
  downloadBlob(new Blob(["\ufeff", toCsv(rows)], { type: "text/csv;charset=utf-8;" }), `${safeName(clientName)}-${month}-categorized-report.csv`);
}

export function exportPdf(rows, clientName, month, insights = []) {
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  const metrics = getMetrics(rows);
  doc.setFillColor(20, 18, 43); doc.rect(0, 0, 842, 595, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22); doc.text(`${clientName} — Marketing Report`, 40, 48);
  doc.setFontSize(10); doc.setTextColor(190, 190, 220); doc.text(`Reporting period: ${month}  •  Generated by AI Report Studio`, 40, 68);
  const cards = [
    ["Total Spend", money(metrics.spend)], ["Revenue", money(metrics.revenue)],
    ["Conversions", number(metrics.conversions)], ["ROAS", metrics.roas == null ? "N/A" : `${metrics.roas.toFixed(2)}x`]
  ];
  cards.forEach((card, i) => {
    const x = 40 + i * 190;
    doc.setFillColor(35, 34, 65); doc.roundedRect(x, 88, 174, 55, 8, 8, "F");
    doc.setFontSize(9); doc.setTextColor(175, 177, 210); doc.text(card[0], x + 12, 108);
    doc.setFontSize(15); doc.setTextColor(255, 255, 255); doc.text(card[1], x + 12, 130);
  });
  doc.setTextColor(255, 255, 255); doc.setFontSize(14); doc.text("Campaign Performance", 40, 174);
  autoTable(doc, {
    startY: 188,
    head: [["Campaign", "Category", "Spend", "Revenue", "Reach", "Clicks", "Conversions", "ROAS"]],
    body: rows.map(r => [r.campaignName, r.category, money(r.spend), money(r.revenue), number(r.reach), number(r.clicks), number(r.conversions), Number(r.spend) > 0 ? `${(Number(r.revenue || 0) / Number(r.spend)).toFixed(2)}x` : "N/A"]),
    theme: "grid",
    styles: { fontSize: 8, cellPadding: 5, textColor: [30, 30, 50] },
    headStyles: { fillColor: [96, 70, 245], textColor: [255, 255, 255] },
    alternateRowStyles: { fillColor: [244, 243, 255] },
    margin: { left: 40, right: 40 }
  });
  let y = (doc.lastAutoTable?.finalY || 300) + 24;
  if (insights.length) {
    if (y > 500) { doc.addPage(); y = 50; }
    doc.setTextColor(255, 255, 255); doc.setFontSize(14); doc.text("AI Insights & Recommendations", 40, y);
    doc.setFontSize(10);
    insights.slice(0, 5).forEach((line, i) => {
      const wrapped = doc.splitTextToSize(`• ${line}`, 740);
      doc.text(wrapped, 44, y + 20 + i * 26);
    });
  }
  doc.save(`${safeName(clientName)}-${month}-report.pdf`);
}

export async function exportPptx(rows, clientName, month, insights = []) {
  const pptx = new pptxgen();
  pptx.layout = "LAYOUT_WIDE";
  pptx.author = "AI Report Studio";
  pptx.subject = "Marketing performance report";
  pptx.title = `${clientName} Marketing Report`;
  pptx.theme = { headFontFace: "Aptos Display", bodyFontFace: "Aptos", lang: "en-IN" };
  const metrics = getMetrics(rows);
  const bg = "111126", panel = "20203B", purple = "6D5DFB", white = "FFFFFF", muted = "B9B9D6", green = "48D597";
  const slide = pptx.addSlide(); slide.background = { color: bg };
  slide.addText("MARKETING PERFORMANCE", { x: .6, y: .55, w: 7, h: .3, fontSize: 11, bold: true, color: green, charSpacing: 2 });
  slide.addText(clientName, { x: .6, y: 1.05, w: 11.4, h: .8, fontSize: 30, bold: true, color: white });
  slide.addText(`Monthly report • ${month}`, { x: .6, y: 1.95, w: 8, h: .35, fontSize: 14, color: muted });
  slide.addText("Prepared with AI Report Studio", { x: .6, y: 6.65, w: 6, h: .25, fontSize: 9, color: muted });

  const cards = [
    ["TOTAL SPEND", money(metrics.spend)], ["REVENUE", money(metrics.revenue)],
    ["CONVERSIONS", number(metrics.conversions)], ["BLENDED ROAS", metrics.roas == null ? "N/A" : `${metrics.roas.toFixed(2)}x`]
  ];
  const summary = pptx.addSlide(); summary.background = { color: bg };
  summary.addText("Executive Summary", { x: .55, y: .35, w: 8, h: .5, fontSize: 24, bold: true, color: white });
  cards.forEach((card, i) => {
    const x = .55 + i * 3.15;
    summary.addShape(pptx.ShapeType.roundRect, { x, y: 1.2, w: 2.85, h: 1.15, rectRadius: .08, fill: { color: panel }, line: { color: "38385B" } });
    summary.addText(card[0], { x: x + .16, y: 1.42, w: 2.5, h: .2, fontSize: 9, color: muted, bold: true });
    summary.addText(card[1], { x: x + .16, y: 1.75, w: 2.5, h: .4, fontSize: 20, color: i === 3 ? green : white, bold: true });
  });
  summary.addText("Key campaign data is shown below. Metrics are calculated from the uploaded dataset.", { x: .6, y: 2.75, w: 11.5, h: .5, fontSize: 12, color: muted });
  const tableSlide = pptx.addSlide(); tableSlide.background = { color: bg };
  tableSlide.addText("Campaign Breakdown", { x: .55, y: .35, w: 8, h: .5, fontSize: 24, bold: true, color: white });
  const tableRows = [
    [{ text: "Campaign", options: { bold: true, color: white, fill: purple } }, { text: "Category", options: { bold: true, color: white, fill: purple } }, { text: "Spend", options: { bold: true, color: white, fill: purple } }, { text: "Revenue", options: { bold: true, color: white, fill: purple } }, { text: "Conversions", options: { bold: true, color: white, fill: purple } }],
    ...rows.slice(0, 12).map(r => [r.campaignName, r.category, money(r.spend), money(r.revenue), number(r.conversions)])
  ];
  tableSlide.addTable(tableRows, { x: .55, y: 1.05, w: 12.1, h: 5.5, border: { color: "3A3A5B", pt: .6 }, color: white, fill: { color: panel }, fontSize: 10, rowH: .34, margin: .08, autoFit: true });
  const insightSlide = pptx.addSlide(); insightSlide.background = { color: bg };
  insightSlide.addText("Insights & Next Steps", { x: .55, y: .35, w: 8, h: .5, fontSize: 24, bold: true, color: white });
  const lines = insights.length ? insights : ["Review campaign performance by category.", "Validate any missing source metrics before making budget decisions.", "Compare results with the previous reporting period when data is available."];
  insightSlide.addText(lines.slice(0, 7).map(s => ({ text: s, options: { bullet: { indent: 16 }, breakLine: true } })), { x: .8, y: 1.25, w: 11.2, h: 4.7, fontSize: 17, color: white, paraSpaceAfterPt: 14, breakLine: false, valign: "mid" });
  await pptx.writeFile({ fileName: `${safeName(clientName)}-${month}-report.pptx` });
}
